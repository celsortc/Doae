    private void carregarItens(CadastroItens cadastroItens) {
        itensDisponiveis = cadastroItens.listar();

        cmbItem.removeAllItems();

        for (Item item : cadastroItens.listar()) {

            cmbItem.addItem(item.getNome());
        }
    }

